/**
 * Resolves WMO code to condition descriptor
 * @param {number} code
 * @param {boolean} isDay
 */
export function getWeatherCondition(code, isDay = 1) {
  const fallback = {
    label: 'Partly Cloudy',
    icon: isDay ? 'CloudSun' : 'CloudMoon',
    nightIcon: 'CloudMoon',
    description: 'Variable cloud conditions',
    gradient: 'from-sky-500/20 via-slate-500/10 to-transparent',
    accentColor: '#0ea5e9',
    advisory: 'Moderate weather conditions.',
  };

  const condition = WEATHER_CONDITIONS[code] || fallback;
  return {
    ...condition,
    resolvedIcon: isDay ? condition.icon : (condition.nightIcon || condition.icon),
  };
}
